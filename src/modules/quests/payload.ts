import { z } from "zod";

/**
 * Category-specific quest content, stored in Quest.payload. Every generator
 * (rule-based now, AI Mentor later) must produce one of these shapes, and it
 * is validated before it is persisted or rendered.
 */
export const questPayloadSchema = z.discriminatedUnion("kind", [
  /** Read from the user's own book. */
  z.object({ kind: z.literal("reading"), pages: z.number().int().min(1).max(200) }),
  /** Deliberate practice of something the user is into. */
  z.object({ kind: z.literal("practice"), topic: z.string().trim().min(1).max(60) }),
  /**
   * A short learning experience delivered inside AROHA. "library" lessons are
   * curated and bundled; "mentor" lessons will be generated by the AI Mentor.
   */
  z.object({
    kind: z.literal("lesson"),
    provider: z.enum(["library", "mentor"]),
    lessonId: z.string().trim().min(1).max(80),
    title: z.string().trim().min(1).max(120),
  }),
  /** Learning from outside media the user chooses. */
  z.object({
    kind: z.literal("media"),
    format: z.enum(["AUDIO", "VIDEO", "COURSE"]),
    topic: z.string().trim().max(60).nullable(),
  }),
  /** A step on one of the user's goals. */
  z.object({
    kind: z.literal("goal"),
    goalId: z.string().max(64).nullable(),
    missionId: z.string().max(64).nullable(),
    href: z.string().max(200),
  }),
  /** Writing or reflection prompts. */
  z.object({ kind: z.literal("prompts"), prompts: z.array(z.string().trim().min(1).max(200)).min(1).max(5) }),
]);

export type QuestPayload = z.infer<typeof questPayloadSchema>;

/** Parses stored JSON defensively; unknown shapes render as no payload. */
export function readPayload(value: unknown): QuestPayload | null {
  const parsed = questPayloadSchema.safeParse(value);
  return parsed.success ? parsed.data : null;
}
